// Generates docs/CODE_INDEX.md: every top-level function, component, const,
// type, interface and class in src/, with signature, export status and line.
// Run with `npm run index:code`. Uses the TypeScript compiler API (no regex).
import ts from 'typescript';
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const ROOT = process.cwd();
const SRC = join(ROOT, 'src');
const OUT = join(ROOT, 'docs', 'CODE_INDEX.md');
const MAX_SIG = 140;

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) return walk(full);
    return /\.(ts|tsx)$/.test(name) && !/\.test\.tsx?$/.test(name) ? [full] : [];
  });
}

const clip = (s) => {
  const flat = s.replace(/\s+/g, ' ').trim();
  return flat.length > MAX_SIG ? `${flat.slice(0, MAX_SIG - 1)}…` : flat;
};

const isExported = (node) =>
  !!ts.getCombinedModifierFlags(node) && (ts.getCombinedModifierFlags(node) & ts.ModifierFlags.Export) !== 0;
const isDefault = (node) => (ts.getCombinedModifierFlags(node) & ts.ModifierFlags.Default) !== 0;

function jsDoc(node) {
  const docs = node.jsDoc;
  if (!docs?.length) return '';
  const c = docs[docs.length - 1].comment;
  return clip(typeof c === 'string' ? c : (c ?? []).map((p) => p.text).join(''));
}

function params(sf, fn) {
  return fn.parameters.map((p) => p.getText(sf)).join(', ');
}

function returnType(sf, fn) {
  return fn.type ? `: ${fn.type.getText(sf)}` : '';
}

function kindOfFn(name, sf, fn) {
  const async = fn.modifiers?.some((m) => m.kind === ts.SyntaxKind.AsyncKeyword) ? 'async ' : '';
  const component = /^[A-Z]/.test(name) && sf.fileName.endsWith('.tsx');
  return `${async}${component ? 'component' : 'function'}`;
}

function entriesFor(file) {
  const text = readFileSync(file, 'utf8');
  const sf = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, file.endsWith('x') ? ts.ScriptKind.TSX : ts.ScriptKind.TS);
  const directive = /^\s*['"]use (client|server)['"]/.exec(text)?.[1] ?? '';
  const line = (n) => sf.getLineAndCharacterOfPosition(n.getStart(sf)).line + 1;
  const out = [];
  const push = (node, name, kind, signature) =>
    out.push({ name, kind, signature: clip(signature), exported: isExported(node) ? (isDefault(node) ? 'default' : 'yes') : '', line: line(node), doc: jsDoc(node) });

  for (const node of sf.statements) {
    if (ts.isFunctionDeclaration(node)) {
      const name = node.name?.text ?? '(default)';
      push(node, name, kindOfFn(name, sf, node), `(${params(sf, node)})${returnType(sf, node)}`);
    } else if (ts.isVariableStatement(node)) {
      for (const d of node.declarationList.declarations) {
        if (!ts.isIdentifier(d.name)) continue;
        const init = d.initializer;
        const name = d.name.text;
        if (init && (ts.isArrowFunction(init) || ts.isFunctionExpression(init))) {
          push(node, name, kindOfFn(name, sf, init), `(${params(sf, init)})${returnType(sf, init)}`);
        } else {
          const t = d.type ? `: ${d.type.getText(sf)}` : init ? ` = ${init.getText(sf)}` : '';
          push(node, name, 'const', t);
        }
      }
    } else if (ts.isInterfaceDeclaration(node)) {
      push(node, node.name.text, 'interface', `{ ${node.members.map((m) => m.name?.getText(sf)).filter(Boolean).join(', ')} }`);
    } else if (ts.isTypeAliasDeclaration(node)) {
      push(node, node.name.text, 'type', `= ${node.type.getText(sf)}`);
    } else if (ts.isClassDeclaration(node)) {
      push(node, node.name?.text ?? '(class)', 'class', `{ ${node.members.map((m) => m.name?.getText(sf)).filter(Boolean).join(', ')} }`);
    } else if (ts.isEnumDeclaration(node)) {
      push(node, node.name.text, 'enum', `{ ${node.members.map((m) => m.name.getText(sf)).join(', ')} }`);
    } else if (ts.isExportAssignment(node)) {
      out.push({ name: 'default', kind: 'export', signature: clip(node.expression.getText(sf)), exported: 'default', line: line(node), doc: '' });
    }
  }
  return { directive, entries: out };
}

const esc = (s) => s.replace(/\|/g, '\\|');
const files = walk(SRC).sort();
const groups = new Map();
let total = 0;
const allNames = [];

for (const file of files) {
  const rel = relative(ROOT, file).split(sep).join('/');
  const area = rel.split('/').slice(0, 3).join('/');
  const { directive, entries } = entriesFor(file);
  total += entries.length;
  entries.forEach((e) => allNames.push({ ...e, file: rel }));
  if (!groups.has(area)) groups.set(area, []);
  groups.get(area).push({ rel, directive, entries });
}

const lines = [
  '# Code index',
  '',
  `Generated by \`npm run index:code\` (scripts/code-index.mjs). Do not edit by hand. ${files.length} files, ${total} top-level symbols in \`src/\` (tests excluded).`,
  '',
  'Columns: **Exp** = exported (`yes` / `default`), **Line** = declaration line. Directive shows `use client` / `use server` boundaries.',
  '',
  '## Contents',
  '',
  ...[...groups.keys()].map((a) => `- [${a}](#${a.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')})`),
  '- [A-Z symbol lookup](#a-z-symbol-lookup)',
  '',
];

for (const [area, list] of groups) {
  lines.push(`## ${area}`, '');
  for (const { rel, directive, entries } of list) {
    lines.push(`### \`${rel}\`${directive ? ` (use ${directive})` : ''}`, '');
    if (!entries.length) { lines.push('_No top-level declarations._', ''); continue; }
    lines.push('| Name | Kind | Exp | Line | Signature | Doc |', '|---|---|---|---|---|---|');
    for (const e of entries) lines.push(`| \`${e.name}\` | ${e.kind} | ${e.exported} | ${e.line} | \`${esc(e.signature)}\` | ${esc(e.doc)} |`);
    lines.push('');
  }
}

lines.push('## A-Z symbol lookup', '', '| Name | Kind | Location |', '|---|---|---|');
for (const e of allNames.sort((a, b) => a.name.localeCompare(b.name))) lines.push(`| \`${e.name}\` | ${e.kind} | \`${e.file}:${e.line}\` |`);
lines.push('');

mkdirSync(join(ROOT, 'docs'), { recursive: true });
writeFileSync(OUT, lines.join('\n'));
console.log(`code-index: ${files.length} files, ${total} symbols -> ${relative(ROOT, OUT)}`);
